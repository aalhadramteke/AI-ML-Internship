# VARIABLES AND DATA TYPES IN PYTHON 

var1= 10                                # Integer
var2= 20.5                              # Float
var3= "Hello, World!"                   # String
var4= True                              # Boolean
var5= [1, 2, 3, 4, 5]                   # List
var6= (1, 2, 3, 4, 5)                   # Tuple
var7= {"name": "John", "age": 30}       # Dictionary
var8= None                              # NoneType
var9= 3 + 4j                            # Complex
var10= b"Hello, Bytes!"                 # Bytes

print(type(var1), type(var2), 
      type(var3), type(var4), 
      type(var5), type(var6), 
      type(var7), type(var8), 
      type(var9), type(var10))

# Here var1, var2, var3, var4, var5, var6, var7, var8, var9, and var10 are variables of different data types in Python. 
# The print statement will output the type of each variable using the type() function.
